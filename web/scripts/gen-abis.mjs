// Generate src/lib/abis.ts from the Foundry build artifacts in ../out.
// Run with: npm run abis   (requires `forge build` to have produced out/)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, "../../out");
const target = resolve(here, "../src/lib/abis.ts");

const contracts = [
  ["assetRegistryAbi", "AssetRegistry"],
  ["saleEscrowAbi", "SaleEscrow"],
  ["royaltyAbi", "RoyaltySplitter"],
  ["licenceAbi", "LicenceToken"],
];

const parts = [
  "// AUTO-GENERATED by web/scripts/gen-abis.mjs from Foundry artifacts.",
  "// Do not edit by hand; run `npm run abis` after `forge build`.",
  "",
];

for (const [exportName, contract] of contracts) {
  const p = resolve(outDir, `${contract}.sol`, `${contract}.json`);
  if (!existsSync(p)) {
    console.error(`Missing artifact: ${p}. Run 'forge build' first.`);
    process.exit(1);
  }
  const art = JSON.parse(readFileSync(p, "utf8"));
  parts.push(`export const ${exportName} = ${JSON.stringify(art.abi, null, 2)} as const;`);
  parts.push("");
}

writeFileSync(target, parts.join("\n"));
console.log(`Wrote ${target}`);
