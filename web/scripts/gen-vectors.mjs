// Generate cross-implementation test vectors with Node/OpenSSL.
// These follow the documented CRC formulas exactly, but are computed with a
// completely different crypto stack from the browser port (@noble/*), so the
// in-app self-test is a real cross-check, not a tautology.
import { createHash, createHmac } from "node:crypto";
import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../src/lib/vectors.json");

const sha = (b) => createHash("sha256").update(b).digest();
const hmac = (k, m) => {
  const kk = Buffer.alloc(64);
  Buffer.from(k).copy(kk, 0, 0, Math.min(32, k.length));
  return createHmac("sha256", kk).update(m).digest();
};
const u64 = (n) => { const b = Buffer.alloc(8); b.writeBigUInt64BE(BigInt(n)); return b; };
const u32 = (n) => { const b = Buffer.alloc(4); b.writeUInt32BE(n >>> 0); return b; };

const seq = (start, len) => Buffer.from(Array.from({ length: len }, (_, i) => (start + i) & 0xff));

const K = seq(0x00, 32);
const N = seq(0x20, 32);
const s = seq(0x40, 32);
const saltD = seq(0x60, 32);
const saltC = seq(0x80, 32);
const D = Buffer.from("MetaTrade-R cross-implementation vector. ".repeat(30));
const beta = 1024;

const tag = (n) => Buffer.from([n]);

const keystream = (kEnc, i, j) => hmac(kEnc, Buffer.concat([tag(0x03), u64(i), u32(j)]));
const plainLeaf = (i, d) => sha(Buffer.concat([tag(0x06), u64(i), d]));
const cipherLeaf = (i, c) => sha(Buffer.concat([tag(0x07), u64(i), c]));

const m = Math.ceil(D.length / beta);
const kEnc = hmac(K, Buffer.from([0x01]));
const C = Buffer.alloc(D.length);
const leafD = [];
const leafC = [];
for (let i = 0; i < m; i++) {
  const start = i * beta;
  const end = Math.min(start + beta, D.length);
  const Di = D.subarray(start, end);
  const Ci = Buffer.alloc(end - start);
  const nWords = Math.ceil(Ci.length / 32);
  for (let j = 0; j < nWords; j++) {
    const ks = keystream(kEnc, i, j);
    const off = j * 32;
    for (let k = 0; k < 32 && off + k < Ci.length; k++) Ci[off + k] = Di[off + k] ^ ks[k];
  }
  Ci.copy(C, start);
  leafD.push(plainLeaf(i, Di));
  leafC.push(cipherLeaf(i, Ci));
}

function merkleRoot(leaves) {
  let level = leaves.slice();
  while (level.length > 1) {
    const next = [];
    for (let i = 0; i < level.length; i += 2) {
      const l = level[i];
      const r = i + 1 < level.length ? level[i + 1] : l;
      next.push(sha(Buffer.concat([tag(0x09), l, r])));
    }
    level = next;
  }
  return level[0];
}

function merkleProof(leaves, index) {
  const proof = [];
  let level = leaves.slice();
  let idx = index;
  while (level.length > 1) {
    const sib = idx % 2 === 0 ? idx + 1 : idx - 1;
    proof.push(sib < level.length ? level[sib] : level[idx]);
    const next = [];
    for (let i = 0; i < level.length; i += 2) {
      const l = level[i];
      const r = i + 1 < level.length ? level[i + 1] : l;
      next.push(sha(Buffer.concat([tag(0x09), l, r])));
    }
    level = next;
    idx = Math.floor(idx / 2);
  }
  return proof;
}

const R_D = merkleRoot(leafD);
const R_C = merkleRoot(leafC);
const hD = sha(Buffer.concat([tag(0x04), saltD, u32(D.length), D]));
const hC = sha(Buffer.concat([tag(0x05), saltC, u32(C.length), C]));
const cK = sha(Buffer.concat([tag(0x08), K, N, s]));

const vectors = {
  _note:
    "Generated by web/scripts/gen-vectors.mjs using Node/OpenSSL. Used by the in-app self-test.",
  standards: {
    sha256_abc: sha(Buffer.from("abc")).toString("hex"),
    sha256_empty: sha(Buffer.from("")).toString("hex"),
    hmac_rfc4231_case1: hmac(
      Buffer.from("0b".repeat(20), "hex"),
      Buffer.from("Hi There"),
    ).toString("hex"),
  },
  asset: {
    beta,
    m,
    K: K.toString("hex"),
    N: N.toString("hex"),
    s: s.toString("hex"),
    saltD: saltD.toString("hex"),
    saltC: saltC.toString("hex"),
    D: D.toString("hex"),
    C: C.toString("hex"),
    leafD: leafD.map((x) => x.toString("hex")),
    leafC: leafC.map((x) => x.toString("hex")),
    R_D: R_D.toString("hex"),
    R_C: R_C.toString("hex"),
    hD: hD.toString("hex"),
    hC: hC.toString("hex"),
    cK: cK.toString("hex"),
    proof0: {
      index: 0,
      proofC: merkleProof(leafC, 0).map((x) => x.toString("hex")),
      proofD: merkleProof(leafD, 0).map((x) => x.toString("hex")),
    },
  },
};

writeFileSync(out, JSON.stringify(vectors, null, 2));
console.log(`Wrote ${out}`);
console.log(`blocks (m) = ${m}, D = ${D.length} bytes`);
